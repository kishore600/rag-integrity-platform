-- RAG Integrity: control-plane ledger (issues, audit history, per-document state, repair plans).
--
-- Lives in its own `ragi` schema. Supabase's REST API only exposes `public` by default, so these
-- tables are not reachable through PostgREST; the app connects with a direct Postgres connection.
-- Row level security is enabled with no policies as a second lock, and anon/authenticated are
-- explicitly stripped of access.
--
-- No document contents are stored here: only ids, hashes, versions, counts and evidence about them.
-- Keep this file in sync with src/ragintegrity/ledger.py (tests/test_schema.py enforces column parity).

create schema if not exists ragi;

create table if not exists ragi.audit_runs (
  id          varchar(36) primary key,
  kind        varchar(16) not null,            -- full | scoped | verify
  "trigger"   varchar(32) not null,            -- manual | api | cli | schedule | repair-verify | ...
  scope       jsonb       not null default '{}'::jsonb,
  status      varchar(16) not null,            -- running | completed | failed
  started_at  timestamptz not null,
  finished_at timestamptz,
  stats       jsonb       not null default '{}'::jsonb,
  error       text
);

create table if not exists ragi.issues (
  id              varchar(32) primary key,     -- deterministic: hash(type, tenant, document, collection)
  type            varchar(32) not null,
  severity        varchar(16) not null,
  status          varchar(16) not null,        -- open | resolved | ignored
  tenant_id       text        not null,
  document_id     text        not null,
  collection      text,
  title           text        not null,
  detail          text        not null,
  evidence        jsonb       not null default '{}'::jsonb,
  action          varchar(32) not null,
  first_seen_at   timestamptz not null,
  last_seen_at    timestamptz not null,
  first_run_id    varchar(36) not null,
  last_run_id     varchar(36) not null,
  resolved_at     timestamptz,
  resolved_run_id varchar(36),
  occurrences     integer     not null default 1,
  reopened_count  integer     not null default 0,
  ignored_reason  text
);
create index if not exists ix_issues_status_sev on ragi.issues (status, severity);
create index if not exists ix_issues_doc        on ragi.issues (tenant_id, document_id);

create table if not exists ragi.issue_events (
  id       integer generated by default as identity primary key,
  issue_id varchar(32) not null,
  run_id   varchar(36),
  ts       timestamptz not null,
  event    varchar(32) not null,               -- opened | reopened | resolved | severity_changed | ignored | unignored
  details  jsonb       not null default '{}'::jsonb
);
create index if not exists ix_issue_events_issue on ragi.issue_events (issue_id);
create index if not exists ix_issue_events_ts    on ragi.issue_events (ts);

create table if not exists ragi.documents (
  tenant_id           text        not null,
  document_id         text        not null,
  status              varchar(16) not null,    -- healthy | degraded | broken | pending | orphaned
  issue_count         integer     not null,
  worst_severity      varchar(16),
  issue_types         jsonb       not null default '[]'::jsonb,
  fingerprint         jsonb       not null default '{}'::jsonb,
  source_uri          text,
  source_hash         text,
  source_version      text,
  size_bytes          integer     not null default 0,
  expected_chunks     integer,
  indexed_chunks      integer     not null default 0,
  manifest_status     text,
  manifest_updated_at text,
  collections         jsonb       not null default '[]'::jsonb,
  source_present      integer     not null,
  manifest_present    integer     not null,
  index_present       integer     not null,
  last_verified_at    timestamptz not null,
  last_run_id         varchar(36) not null,
  primary key (tenant_id, document_id)
);
create index if not exists ix_documents_status on ragi.documents (status);

create table if not exists ragi.repair_plans (
  id         varchar(36) primary key,
  status     varchar(24) not null,             -- draft | triggered | partial | failed | cleanup_pending | cleanup_triggered | completed
  created_at timestamptz not null,
  updated_at timestamptz not null,
  items      jsonb       not null default '[]'::jsonb,
  summary    jsonb       not null default '{}'::jsonb
);

create table if not exists ragi.repair_events (
  id      integer generated by default as identity primary key,
  plan_id varchar(36) not null,
  ts      timestamptz not null,
  event   varchar(32) not null,
  details jsonb       not null default '{}'::jsonb
);
create index if not exists ix_repair_events_plan on ragi.repair_events (plan_id);

create table if not exists ragi.query_log (
  id                integer generated by default as identity primary key,
  ts                timestamptz not null,
  tenant_id         text        not null,
  query_hash        varchar(64),               -- query text is hashed, never stored
  retrieved_doc_ids jsonb       not null default '[]'::jsonb
);
create index if not exists ix_query_log_ts on ragi.query_log (ts);

-- Lock the schema down. (Roles only exist on Supabase, hence the guard.)
alter table ragi.audit_runs    enable row level security;
alter table ragi.issues        enable row level security;
alter table ragi.issue_events  enable row level security;
alter table ragi.documents     enable row level security;
alter table ragi.repair_plans  enable row level security;
alter table ragi.repair_events enable row level security;
alter table ragi.query_log     enable row level security;

do $$
declare r text;
begin
  foreach r in array array['anon', 'authenticated'] loop
    if exists (select 1 from pg_roles where rolname = r) then
      execute format('revoke all on schema ragi from %I', r);
      execute format('revoke all on all tables in schema ragi from %I', r);
      execute format('revoke all on all sequences in schema ragi from %I', r);
    end if;
  end loop;
end $$;
